/*
 * dist/apk/apk-info.js (D-059): tells Settings → System which Android APKs are in the folder, newest first.
 * Written by tools/build.cjs (every build) and tools/build-apk.cjs (after a new APK). It is a classic script
 * (not JSON) because the app runs from file://, where fetch() of local files is not allowed.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const APK_RE = /^rj-ims-(\d+\.\d+\.\d+)\.apk$/;
const verNum = (v) => v.split('.').map((x) => parseInt(x, 10) || 0);
const newestFirst = (a, b) => { const x = verNum(a), y = verNum(b); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return y[i] - x[i]; return 0; };

/** Versions of the APKs in `apkDir`, plus `extraVersion` (an APK about to be added), newest first. */
function apkVersions(apkDir, extraVersion) {
  const found = fs.existsSync(apkDir) ? fs.readdirSync(apkDir).map((f) => (f.match(APK_RE) || [])[1]).filter(Boolean) : [];
  if (extraVersion && !found.includes(extraVersion)) found.push(extraVersion);
  return found.sort(newestFirst);
}

function apkInfoScript(versions) {
  const all = versions.map((v) => ({ version: v, file: `apk/rj-ims-${v}.apk` }));
  const info = { latest: all[0] || null, all };
  return `/* Generated by the build (D-059) — Android APKs in this folder, newest first. */\nwindow.RJ_APK = ${JSON.stringify(info)};\n`;
}

/** Writes <outDir>/apk/apk-info.js for the APKs in <outDir>/apk (plus extraVersion). Returns the script text. */
function writeApkInfo(outDir, extraVersion) {
  const dir = path.join(outDir, 'apk');
  fs.mkdirSync(dir, { recursive: true });
  const text = apkInfoScript(apkVersions(dir, extraVersion));
  fs.writeFileSync(path.join(dir, 'apk-info.js'), text);
  return text;
}

module.exports = { apkVersions, apkInfoScript, writeApkInfo, APK_RE };
